import { jsPDF } from 'jspdf';
import type { ComplaintRecord } from '../types/campusfix';

export function downloadComplaintPdf(complaint: ComplaintRecord): void {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 48;
  const maxWidth = pageWidth - margin * 2;
  let y = 52;

  // Header Banner
  doc.setFillColor(20, 43, 74); // #142B4A
  doc.rect(0, 0, pageWidth, 88, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.text('CAMPUSFIX', margin, 42);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(50, 197, 244); // #32C5F4
  doc.text('Smart Campus Issue Reporting & Management System', margin, 60);

  doc.setTextColor(226, 232, 240);
  doc.setFontSize(10);
  doc.text(`ID: ${complaint.complaintId}`, pageWidth - margin, 42, { align: 'right' });
  doc.text(`Status: ${complaint.status}`, pageWidth - margin, 60, { align: 'right' });

  y = 122;

  // Title
  doc.setTextColor(20, 43, 74);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  const titleLines = doc.splitTextToSize(complaint.title, maxWidth);
  doc.text(titleLines, margin, y);
  y += titleLines.length * 20 + 14;

  // Metadata grid
  const submittedStr = complaint.createdAt
    ? complaint.createdAt.toLocaleString()
    : 'Recently submitted';
  const updatedStr = complaint.updatedAt
    ? complaint.updatedAt.toLocaleString()
    : submittedStr;

  const metaRows: [string, string][] = [
    ['Complaint ID', complaint.complaintId],
    ['Reported By', `${complaint.studentName}${complaint.studentIdNumber ? ` (${complaint.studentIdNumber})` : ''}`],
    ['Student Email', complaint.studentEmail],
    ['Category', complaint.category],
    ['Priority Level', complaint.priority],
    ['Campus Building', complaint.building],
    ['Specific Location', complaint.location],
    ['Submitted On', submittedStr],
    ['Last Updated', updatedStr],
    ['Current Status', complaint.status],
  ];

  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.75);

  metaRows.forEach(([label, val]) => {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9.5);
    doc.setTextColor(100, 116, 139);
    doc.text(label.toUpperCase(), margin, y);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10.5);
    doc.setTextColor(20, 43, 74);
    const wrappedVal = doc.splitTextToSize(val || '—', maxWidth - 150);
    doc.text(wrappedVal, margin + 150, y);

    const rowHeight = Math.max(18, wrappedVal.length * 14);
    doc.line(margin, y + rowHeight - 6, pageWidth - margin, y + rowHeight - 6);
    y += rowHeight + 6;
  });

  y += 12;

  // Description
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(20, 43, 74);
  doc.text('Issue Description', margin, y);
  y += 16;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10.5);
  doc.setTextColor(51, 65, 85);
  const descLines = doc.splitTextToSize(complaint.description, maxWidth);
  doc.text(descLines, margin, y);
  y += descLines.length * 14 + 18;

  // Admin remarks
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(20, 43, 74);
  doc.text('Administrator Remarks', margin, y);
  y += 16;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10.5);
  doc.setTextColor(51, 65, 85);
  const remarkText = complaint.adminRemarks || 'No administrator remarks added yet.';
  const remarkLines = doc.splitTextToSize(remarkText, maxWidth);
  doc.text(remarkLines, margin, y);
  y += remarkLines.length * 14 + 20;

  // Timeline
  if (complaint.history.length > 0 && y < 720) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(20, 43, 74);
    doc.text('Status Timeline', margin, y);
    y += 16;

    complaint.history.forEach((entry) => {
      if (y > 760) return;
      const dateStr = new Date(entry.timestamp).toLocaleString();
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9.5);
      doc.setTextColor(56, 103, 245);
      doc.text(`${entry.status} · ${dateStr}`, margin, y);
      y += 13;

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(9.5);
      doc.setTextColor(71, 85, 105);
      const noteLines = doc.splitTextToSize(`${entry.note} (${entry.actorName})`, maxWidth);
      doc.text(noteLines, margin, y);
      y += noteLines.length * 12 + 8;
    });
  }

  // Footer
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(148, 163, 184);
  doc.text(
    `Generated by CampusFix on ${new Date().toLocaleString()} · Report It. Track It. Fix It.`,
    margin,
    doc.internal.pageSize.getHeight() - 30
  );

  doc.save(`CampusFix_${complaint.complaintId}.pdf`);
}
